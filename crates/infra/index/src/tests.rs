#[test]
fn spawn_returns_before_the_build_and_reaches_ready() {
    let dir = project();
    let (tx, rx) = std::sync::mpsc::channel();
    let idx = spawn(
        IndexOptions::new(dir.path()),
        search(dir.path()),
        Some(Box::new(move |r: &crate::BuildReport| {
            let _ = tx.send(r.files);
        })),
    );
    // Queries work at any point of the build.
    let _ = idx.symbols("Engine", None, None, 5).expect("symbols");
    assert_eq!(rx.recv_timeout(Duration::from_secs(30)).expect("ready"), 8);
    assert_eq!(idx.state(), IndexState::Ready);
}

