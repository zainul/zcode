#[test]
fn an_edit_made_outside_zcode_is_seen_on_the_next_query() {
    let dir = project();
    let idx = index(dir.path());
    write(
        dir.path(),
        "py/models.py",
        "class User:\n    def persist(self):\n        pass\n",
    );
    touch_later(dir.path(), "py/models.py");
    let hits = idx.symbols("persist", None, None, 5).expect("symbols");
    // A name the stale record lacks is found by the turn-start rescan…
    assert!(hits.is_empty() || hits[0].qualified == "User.persist");
    idx.rescan_changed();
    assert_eq!(
        idx.symbols("persist", None, None, 5)
            .expect("symbols")
            .len(),
        1
    );
    // …and a stale hit is refreshed by the query that returns it.
    write(
        dir.path(),
        "web/util.ts",
        "\nexport function helper() { return 2; }\n",
    );
    touch_later(dir.path(), "web/util.ts");
    let hits = idx.symbols("helper", None, None, 5).expect("symbols");
    assert_eq!(hits[0].name_line, 2);
}

#[test]
fn a_second_build_reuses_unchanged_files_and_reparses_only_the_touched_one() {
    let dir = project();
    let idx = index(dir.path());
    let first = idx.parses();
    assert!(first >= 6);
    touch_later(dir.path(), "src/lib.rs"); // same content: restamped, not parsed
    write(dir.path(), "web/util.ts", "export function helper2() {}\n");
    touch_later(dir.path(), "web/util.ts");
    let report = idx.build();
    assert_eq!(idx.parses() - first, 1);
    assert_eq!(report.parsed, 1);
}

