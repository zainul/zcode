#[test]
fn a_corrupt_or_foreign_store_is_discarded_and_rebuilt() {
    let dir = project();
    let idx = index(dir.path());
    let path = idx.options().store_path.clone();
    drop(idx);
    let bytes = std::fs::read(&path).expect("read");
    // Every truncation must be rejected, never panic.
    for cut in [0, 3, 10, bytes.len() / 2, bytes.len() - 1] {
        assert!(store::decode(&bytes[..cut]).is_err(), "cut at {cut}");
    }
    let mut other = bytes.clone();
    other[6] ^= 0xff; // extractor version
    assert!(store::decode(&other).is_err());
    std::fs::write(&path, b"garbage").expect("write");
    let fresh = index(dir.path());
    assert!(fresh.parses() >= 6);
    assert_eq!(fresh.stats().files, 8);
}

